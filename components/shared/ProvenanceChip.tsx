'use client';

import React, { useState } from 'react';
import { cn } from '@/lib/utils';
import { ShieldCheck, HelpCircle, Calculator, Sparkles } from 'lucide-react';
import { ProvenanceType } from '@/lib/types';

export interface ProvenanceChipProps {
  type: ProvenanceType;
  customNote?: string;
  className?: string;
}

export function ProvenanceChip({ type, customNote, className }: ProvenanceChipProps) {
  const [showTooltip, setShowTooltip] = useState(false);

  const configs: Record<ProvenanceType, { icon: React.ReactNode; tooltip: string; style: string }> = {
    Confirmed: {
      icon: <ShieldCheck className="w-3 h-3 text-[#1E6B52]" />,
      tooltip: 'Confirmed: Verified contractual record or user-stamped fact.',
      style: 'bg-[#E1F6EE] text-[#1E6B52] border-[#C3E8DC]',
    },
    Assumption: {
      icon: <HelpCircle className="w-3 h-3 text-[#875C05]" />,
      tooltip: 'Assumption: Default benchmark or estimated value. Subject to change.',
      style: 'bg-[#FDF3D6] text-[#875C05] border-[#F7E19D]',
    },
    Calculated: {
      icon: <Calculator className="w-3 h-3 text-[#544393]" />,
      tooltip: 'Calculated: Computed deterministically by pure TypeScript engine logic.',
      style: 'bg-[#EDEAFB] text-[#544393] border-[#D9D2F5]',
    },
    'AI suggestion': {
      icon: <Sparkles className="w-3 h-3 text-[#9C4221]" />,
      tooltip: 'AI suggestion: Generated by LLM parsing or drafting. Requires creator approval.',
      style: 'bg-[#FDECDA] text-[#9C4221] border-[#F8D2BA]',
    },
  };

  const current = configs[type] || configs.Assumption;
  const tooltipText = customNote || current.tooltip;

  return (
    <div
      className="relative inline-flex items-center"
      onMouseEnter={() => setShowTooltip(true)}
      onMouseLeave={() => setShowTooltip(false)}
      onFocus={() => setShowTooltip(true)}
      onBlur={() => setShowTooltip(false)}
    >
      <span
        tabIndex={0}
        className={cn(
          'inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-mono font-semibold border cursor-help select-none transition-all shadow-[0_1px_2px_rgba(60,50,30,0.03)]',
          current.style,
          className
        )}
      >
        {current.icon}
        <span>{type}</span>
      </span>

      {showTooltip && (
        <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 z-50 w-56 p-3 rounded-xl bg-[#FCFBF7] border border-[#EDE6D3] text-[#1F1F23] text-[11px] leading-relaxed shadow-[0_4px_12px_-2px_rgba(60,50,30,0.08),0_12px_28px_-4px_rgba(60,50,30,0.1)] pointer-events-none animate-in fade-in zoom-in-95 duration-100">
          <p className="font-sans font-medium">{tooltipText}</p>
          <div className="absolute top-full left-1/2 -translate-x-1/2 -mt-[1px] border-4 border-transparent border-t-[#EDE6D3]" />
        </div>
      )}
    </div>
  );
}
