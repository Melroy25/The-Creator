'use client';

import React, { useState } from 'react';
import { cn } from '@/lib/utils';
import { ShieldCheck, HelpCircle, Calculator, Sparkles } from 'lucide-react';
import { ProvenanceType } from '@/lib/types';

export interface ProvenanceChipProps {
  type: ProvenanceType;
  customNote?: string;
  className?: string;
}

export function ProvenanceChip({ type, customNote, className }: ProvenanceChipProps) {
  const [showTooltip, setShowTooltip] = useState(false);

  const configs: Record<ProvenanceType, { icon: React.ReactNode; tooltip: string; style: string }> = {
    Confirmed: {
      icon: <ShieldCheck className="w-3 h-3 text-status-done-text" />,
      tooltip: 'Confirmed: Verified contractual record or user-stamped fact.',
      style: 'bg-status-done-bg text-status-done-text border-status-done-border',
    },
    Assumption: {
      icon: <HelpCircle className="w-3 h-3 text-status-risk-text" />,
      tooltip: 'Assumption: Default benchmark or estimated value. Subject to change.',
      style: 'bg-status-risk-bg text-status-risk-text border-status-risk-border',
    },
    Calculated: {
      icon: <Calculator className="w-3 h-3 text-accent-strong" />,
      tooltip: 'Calculated: Computed deterministically by pure TypeScript engine logic.',
      style: 'bg-accent-tint text-accent-strong border-accent/20',
    },
    'AI suggestion': {
      icon: <Sparkles className="w-3 h-3 text-status-progress-text" />,
      tooltip: 'AI suggestion: Generated by LLM brief parsing. Requires creator approval.',
      style: 'bg-status-progress-bg text-status-progress-text border-status-progress-border',
    },
  };

  const current = configs[type] || configs.Assumption;
  const tooltipText = customNote || current.tooltip;

  return (
    <div
      className="relative inline-flex items-center"
      onMouseEnter={() => setShowTooltip(true)}
      onMouseLeave={() => setShowTooltip(false)}
      onFocus={() => setShowTooltip(true)}
      onBlur={() => setShowTooltip(false)}
    >
      <span
        tabIndex={0}
        className={cn(
          'inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-mono font-semibold border cursor-help select-none transition-all shadow-sm',
          current.style,
          className
        )}
      >
        {current.icon}
        <span>{type}</span>
      </span>

      {showTooltip && (
        <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-2 z-50 w-56 p-3 rounded-xl bg-surface border border-border text-text-primary text-[11px] leading-relaxed shadow-drawer pointer-events-none animate-in fade-in zoom-in-95 duration-100">
          <p className="font-sans font-medium">{tooltipText}</p>
          <div className="absolute top-full left-1/2 -translate-x-1/2 -mt-[1px] border-4 border-transparent border-t-border" />
        </div>
      )}
    </div>
  );
}
