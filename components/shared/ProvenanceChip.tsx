'use client';

import React, { useState } from 'react';
import { cn } from '@/lib/utils';
import { ShieldCheck, HelpCircle, Calculator, Sparkles } from 'lucide-react';
import { ProvenanceType } from '@/lib/types';

export interface ProvenanceChipProps {
  type: ProvenanceType;
  customNote?: string;
  className?: string;
}

export function ProvenanceChip({ type, customNote, className }: ProvenanceChipProps) {
  const [showTooltip, setShowTooltip] = useState(false);

  const configs: Record<ProvenanceType, { icon: React.ReactNode; tooltip: string; style: string }> = {
    Confirmed: {
      icon: <ShieldCheck className="w-3 h-3 text-emerald-400" />,
      tooltip: 'Confirmed: Verified contractual record or user-stamped fact.',
      style: 'bg-emerald-500/10 text-emerald-300 border-emerald-500/25',
    },
    Assumption: {
      icon: <HelpCircle className="w-3 h-3 text-amber-400" />,
      tooltip: 'Assumption: Default benchmark or estimated value. Subject to change.',
      style: 'bg-amber-500/10 text-amber-300 border-amber-500/25',
    },
    Calculated: {
      icon: <Calculator className="w-3 h-3 text-cyan-400" />,
      tooltip: 'Calculated: Computed deterministically by pure TypeScript engine logic.',
      style: 'bg-cyan-500/10 text-cyan-300 border-cyan-500/25',
    },
    'AI suggestion': {
      icon: <Sparkles className="w-3 h-3 text-purple-400" />,
      tooltip: 'AI suggestion: Generated by LLM parsing or drafting. Requires creator approval.',
      style: 'bg-purple-500/10 text-purple-300 border-purple-500/25',
    },
  };

  const current = configs[type] || configs.Assumption;
  const tooltipText = customNote || current.tooltip;

  return (
    <div
      className="relative inline-flex items-center"
      onMouseEnter={() => setShowTooltip(true)}
      onMouseLeave={() => setShowTooltip(false)}
      onFocus={() => setShowTooltip(true)}
      onBlur={() => setShowTooltip(false)}
    >
      <span
        tabIndex={0}
        className={cn(
          'inline-flex items-center gap-1 px-2 py-0.5 rounded-md text-[10px] font-mono font-medium border cursor-help select-none transition-all',
          current.style,
          className
        )}
      >
        {current.icon}
        <span>{type}</span>
      </span>

      {showTooltip && (
        <div className="absolute bottom-full left-1/2 -translate-x-1/2 mb-1.5 z-50 w-48 p-2 rounded-lg bg-[#0F1424] border border-white/15 text-slate-200 text-[11px] leading-tight shadow-xl pointer-events-none animate-in fade-in zoom-in-95 duration-100">
          <p className="font-sans">{tooltipText}</p>
          <div className="absolute top-full left-1/2 -translate-x-1/2 -mt-[1px] border-4 border-transparent border-t-[#0F1424]" />
        </div>
      )}
    </div>
  );
}
